#include "util/keysym.h"

static const uint16_t koi[32] = {
    0x44E, 0x430, 0x431, 0x446, 0x434, 0x435, 0x444, 0x433, 0x445, 0x438, 0x439, 0x43A, 0x43B, 0x43C, 0x43D, 0x43E,
    0x43F, 0x44F, 0x440, 0x441, 0x442, 0x443, 0x436, 0x432, 0x44C, 0x44B, 0x437, 0x448, 0x44D, 0x449, 0x447, 0x44A};

uint32_t ks_to_cp(uint32_t ks)
{
    if (ks >= 0x20 && ks <= 0x7e) return ks;
    if (ks >= 0xa0 && ks <= 0xff) return ks;
    if (ks >= 0xffb0 && ks <= 0xffb9) return '0' + (ks - 0xffb0);
    if (ks >= 0x6c0 && ks <= 0x6df) return koi[ks - 0x6c0];
    if (ks >= 0x6e0 && ks <= 0x6ff) return koi[ks - 0x6e0] - 0x20u;
    if (ks == 0x6a3) return 0x451;
    if (ks == 0x6b3) return 0x401;
    if (ks >= 0x1000000 && ks <= 0x110ffff) return ks - 0x1000000;
    return 0;
}
